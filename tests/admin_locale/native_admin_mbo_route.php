<?php

declare(strict_types=1);

/**
 * Restricts the MBO native request to the installed module route and the
 * authenticated session token returned by the real Admin HTTP login.
 */
final class NativeAdminMboRoute
{
    private const MODULE_ROUTE_PATH = '/modules/mbo/themes/catalog/';
    private const ADMIN_ROUTE_PATH = '/admin-kuranea/index.php/modules/mbo/themes/catalog/';

    public static function nativeTargetUri(string $nativeSessionToken): string
    {
        self::requireNativeToken($nativeSessionToken);

        return self::ADMIN_ROUTE_PATH . '?_token=' . rawurlencode($nativeSessionToken);
    }

    /**
     * Validate the actual installed router output, then use its route path with
     * the CSRF token read from the authenticated native Admin page. Router::generate
     * can return an empty token before a KernelBrowser request is on RequestStack.
     */
    public static function canonicalizeGeneratedUri(string $generatedUri, string $nativeSessionToken): string
    {
        self::requireNativeToken($nativeSessionToken);
        $parts = parse_url($generatedUri);
        if (!is_array($parts) || isset($parts['scheme']) || isset($parts['host'])
            || isset($parts['user']) || isset($parts['pass']) || isset($parts['fragment'])) {
            throw new RuntimeException('native_mbo_route_contract_mismatch');
        }

        $path = $parts['path'] ?? null;
        if (!is_string($path) || !in_array($path, [self::MODULE_ROUTE_PATH, self::ADMIN_ROUTE_PATH], true)) {
            throw new RuntimeException('native_mbo_route_contract_mismatch');
        }

        if (array_key_exists('query', $parts)) {
            $query = $parts['query'];
            if (!is_string($query) || !preg_match('/\A_token=([A-Za-z0-9_.-]{0,336})\z/D', $query, $matches)) {
                throw new RuntimeException('native_mbo_route_contract_mismatch');
            }
            $generatedToken = $matches[1];
            // CsrfTokenManager masks the same stored session token on every
            // getToken() call, so a token generated by this fresh CLI kernel can
            // differ from the real authenticated HTTP page's still-valid token.
            if ($generatedToken !== '' && !NativeAdminHttpLogin::isSymfonyUriSafeToken($generatedToken)) {
                throw new RuntimeException('native_mbo_route_contract_mismatch');
            }
        }

        return self::nativeTargetUri($nativeSessionToken);
    }

    private static function requireNativeToken(string $token): void
    {
        if (!class_exists(NativeAdminHttpLogin::class)
            || !NativeAdminHttpLogin::isSymfonyUriSafeToken($token)) {
            throw new RuntimeException('native_mbo_session_token_invalid');
        }
    }
}
